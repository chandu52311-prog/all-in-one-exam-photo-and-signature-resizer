-- ExamResizer live government recruitment registry
create table if not exists public.live_job_alerts (
  id text primary key,
  authority text,
  organization text,
  title text not null,
  exam_name text,
  notification_number text,
  notification_ref text,
  posts text,
  category text not null,
  state text,
  qualification text,
  age_limit text,
  fee text,
  vacancies text,
  application_start_date timestamptz,
  closing_date timestamptz,
  closing_at timestamptz,
  last_date timestamptz,
  exam_date timestamptz,
  released_at timestamptz,
  official_notification_url text,
  notification_pdf_url text,
  application_url text,
  application_url_verified boolean not null default false,
  official_portal text,
  source_url text,
  source_id text,
  verified_at timestamptz,
  verification_status text not null default 'pending',
  is_government_employer boolean not null default false,
  disabled boolean not null default false,
  status text not null default 'Awaiting Official Verification',
  archived_at timestamptz,
  archive_reason text,
  content_hash text,
  preset_target text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.recruitment_automation_logs (
  id bigint generated by default as identity primary key,
  source_id text,
  run_started_at timestamptz not null default now(),
  run_finished_at timestamptz,
  records_discovered integer not null default 0,
  records_upserted integer not null default 0,
  records_archived integer not null default 0,
  success boolean not null default false,
  error_message text,
  details jsonb
);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_live_job_alerts_updated_at on public.live_job_alerts;
create trigger trg_live_job_alerts_updated_at
before update on public.live_job_alerts
for each row execute function public.set_updated_at();

alter table public.live_job_alerts enable row level security;
alter table public.recruitment_automation_logs enable row level security;

drop policy if exists "Public can read verified active or archived records" on public.live_job_alerts;
create policy "Public can read verified active or archived records"
on public.live_job_alerts for select
to anon, authenticated
using (
  verification_status = 'verified'
  and is_government_employer = true
  and disabled = false
);

drop policy if exists "Admins manage live job alerts" on public.live_job_alerts;
create policy "Admins manage live job alerts"
on public.live_job_alerts for all
to authenticated
using (coalesce(auth.jwt()->'app_metadata'->>'role', '') = 'admin')
with check (coalesce(auth.jwt()->'app_metadata'->>'role', '') = 'admin');

drop policy if exists "Admins read automation logs" on public.recruitment_automation_logs;
create policy "Admins read automation logs"
on public.recruitment_automation_logs for select
to authenticated
using (coalesce(auth.jwt()->'app_metadata'->>'role', '') = 'admin');

drop policy if exists "Admins manage automation logs" on public.recruitment_automation_logs;
create policy "Admins manage automation logs"
on public.recruitment_automation_logs for insert, update
to authenticated
with check (coalesce(auth.jwt()->'app_metadata'->>'role', '') = 'admin');

create or replace function public.archive_expired_live_job_alerts()
returns integer language plpgsql security definer set search_path = public as $$
declare affected_count integer;
begin
  update public.live_job_alerts
  set status = 'Application Closed',
      archive_reason = 'Application Closed',
      archived_at = coalesce(archived_at, now()),
      updated_at = now()
  where coalesce(closing_at, closing_date, last_date) is not null
    and coalesce(closing_at, closing_date, last_date) <= now()
    and status is distinct from 'Application Closed';
  get diagnostics affected_count = row_count;
  return affected_count;
end;
$$;

grant execute on function public.archive_expired_live_job_alerts() to authenticated;
